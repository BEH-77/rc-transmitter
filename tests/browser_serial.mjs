import assert from 'node:assert/strict'
import { browser, installSerialMock, wait } from './browser_helpers.mjs'
const b = await browser()
const {evaluate,command,click,text,press,move,release,values}=b
try {
  await command('Page.addScriptToEvaluateOnNewDocument',{source:`(${installSerialMock.toString()})()`})
  await command('Page.reload',{ignoreCache:true}); await wait(450)
  await click('.primary-button'); await wait(150)
  await click('.reset-button'); await wait(100)
  assert.equal(await evaluate('__serialMock.state.baud'),115200)
  assert.equal(await evaluate('document.querySelector(".enable-button").disabled'),true,'center throttle cannot enable')
  // A: each independent channel reaches actual writer, preview ACK and UI; outputs remain safe.
  for(const [index,dx,dy,channel] of [[1,1,0,0],[1,0,-1,1],[0,0,-1,2],[0,1,0,3]]){
    const travel=await evaluate(`document.querySelectorAll('.stick-pad')[${index}].clientWidth-52`)
    const p=await press(index);await move(p,dx*travel/4,dy*travel/4);await wait(100)
    const requested=await values();assert.equal(requested[channel],1750)
    const preview=await evaluate('__serialMock.state.preview');assert.deepEqual(preview,requested)
    assert.ok(await evaluate(`__serialMock.state.raw.includes(${JSON.stringify('PREVIEW,'+requested.join(',')+'\n')})`))
    assert.deepEqual(await evaluate('__serialMock.state.applied'),[1500,1500,1000,1500])
    assert.match(await text('[data-testid="preview-ack"]'),new RegExp(String(requested[channel])))
    await release(p,dx*travel/4,dy*travel/4);await wait(100)
    assert.deepEqual(await values(),[1500,1500,1500,1500])
    assert.deepEqual(await evaluate('__serialMock.state.preview'),[1500,1500,1500,1500])
  }
  // B: hold minimum through ENABLE. No center throttle can leak during activation.
  const p=await press(0);await move(p,0,500);await wait(80)
  const before=await evaluate('__serialMock.state.raw.length')
  await click('.enable-button');await wait(120)
  assert.match(await text('.safety-state strong'),/ENABLED/)
  assert.deepEqual(await evaluate('__serialMock.state.applied'),[1500,1500,1000,1500])
  assert.ok(await evaluate(`__serialMock.state.raw.slice(${before}).filter(x=>x.startsWith('RC,')).every(x=>x==='RC,1500,1500,1000,1500\\n')`))
  // Move from the original drag origin; then all channels simultaneously via real touch input below.
  await move(p,25,-30);await wait(100)
  const active=await values()
  assert.deepEqual(await evaluate('__serialMock.state.applied'),active)
  assert.equal(await text('.ack-box code'),active.join(' / '))
  assert.ok(await evaluate(`__serialMock.state.raw.includes(${JSON.stringify('RC,'+active.join(',')+'\n')})`))
  // C/D: left release centers REQUESTED but locks outputs before center throttle control.
  await release(p,25,-30);await wait(120)
  assert.deepEqual(await values(),[1500,1500,1500,1500])
  assert.deepEqual(await evaluate('__serialMock.state.applied'),[1500,1500,1000,1500])
  assert.match(await text('.safety-state strong'),/STOP/)
  assert.deepEqual(await evaluate('__serialMock.state.preview'),[1500,1500,1500,1500])
  // Diagnostics continue while latched; reset never enables.
  await click('.reset-button');await wait(100);assert.match(await text('.safety-state strong'),/LOCKED/)
  // Simultaneous four-channel changes through actual touch events and mocked USB bytes.
  await command('Emulation.setTouchEmulationEnabled',{enabled:true,maxTouchPoints:2})
  const left=await b.point(0), right=await b.point(1)
  const half=await evaluate("(document.querySelector('.stick-pad').clientWidth-52)/2")
  await command('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{...left,id:1}]})
  await command('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:left.x,y:left.y+half,id:1}]})
  await wait(80);await click('.enable-button');await wait(100)
  assert.match(await text('.safety-state strong'),/ENABLED/)
  await command('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:left.x,y:left.y+half,id:1},{...right,id:2}]})
  await command('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:left.x+20,y:left.y-25,id:1},{x:right.x-30,y:right.y+20,id:2}]})
  await wait(100)
  const simultaneous=await values()
  assert.ok(simultaneous.every(x=>x!==1500))
  assert.deepEqual(await evaluate('__serialMock.state.applied'),simultaneous)
  assert.ok(await evaluate(`__serialMock.state.raw.includes(${JSON.stringify('RC,'+simultaneous.join(',')+'\n')})`))
  await command('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});await wait(100)
  assert.deepEqual(await values(),[1500,1500,1500,1500])
  assert.deepEqual(await evaluate('__serialMock.state.applied'),[1500,1500,1000,1500])
  await command('Emulation.setTouchEmulationEnabled',{enabled:false})
  await click('.reset-button');await wait(100)
  await evaluate('__serialMock.reboot()');await wait(100);assert.match(await text('.safety-state strong'),/LOCKED/)
  await click('.secondary-button');await wait(150);assert.match(await text('.topbar-status'),/OFFLINE/)
  await click('.primary-button');await wait(100);assert.match(await text('.topbar-status'),/CONNECTED/)
  await evaluate('__serialMock.usbLoss()');await wait(150);assert.match(await text('.topbar-status'),/OFFLINE/)
  await evaluate('__serialMock.state.failOpen=true');await click('.primary-button');await wait(100)
  assert.match(await text('.terminal-lines'),/Mock open failure/)
  await click('.primary-button');await wait(100)
  await evaluate('__serialMock.state.rejectNext=true');await wait(180)
  assert.match(await text('.topbar-status'),/OFFLINE/)
  await click('.primary-button');await wait(100);await click('.reset-button');await wait(80)
  await evaluate('__serialMock.state.delay=-1');await wait(900)
  assert.match(await text('.topbar-status'),/OFFLINE/,'stalled write must retire connection')
  await evaluate('__serialMock.state.delay=0;__serialMock.release()');await wait(500)
  assert.equal(await evaluate('__serialMock.state.maximum'),1)
  assert.ok(await evaluate('__serialMock.state.raw.every(x=>x.endsWith("\\n"))'),'actual writer bytes must end in newline')
  console.log('Mock USB browser flow passed: four preview channels, actual bytes/ACK, low-throttle enable, current active RC, release STOP, reset/reboot, disconnect/reconnect, rejected/stalled writes')
} finally {b.close()}
